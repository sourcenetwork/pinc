//! Model-based tests: the cases `scripts/mbt.py` writes from a TLC state graph, read back.
//!
//! A case file is ndjson. Its first line describes the graph: the `constants` of the TLC config, the `init` state and
//! the counts (`states`, `leaves`, `edges`, `cases`, `steps`). Every further line is one case, a path from the
//! initial state: `{"case": i, "steps": [{"call": "CallHold", "args": [...], "state": {...}}, ...]}`, each step one
//! call of the model with its arguments (the model's result among them) and the model's whole state after it. A test
//! drives the real code along every case and compares after every step.
//!
//! The files are generated by `scripts/proofs.sh` into the directory named by `PINC_MBT_DIR`; [`mbt_cases`] returns
//! `None` when the variable is unset, so a plain test run skips the model-based tests.

use std::fmt;
use std::io::{BufRead, BufReader};

/// A JSON value, as the case files hold them: integers only, no floats.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Json {
    /// `null`.
    Null,
    /// `true` or `false`.
    Bool(bool),
    /// An integer.
    Int(i128),
    /// A string.
    Str(String),
    /// An array (a TLA+ sequence or set).
    Arr(Vec<Self>),
    /// An object (a TLA+ record), fields in their order.
    Obj(Vec<(String, Self)>),
}

impl Json {
    /// Parse one JSON text.
    ///
    /// # Errors
    /// A description of the first byte that is not valid JSON (or a float).
    pub fn parse(s: &str) -> Result<Self, String> {
        let mut p = Parser { s: s.as_bytes(), i: 0 };
        let v = p.value()?;
        p.ws();
        if p.i == p.s.len() {
            Ok(v)
        } else {
            Err(format!("trailing text at byte {}", p.i))
        }
    }

    /// The field `key` of an object.
    pub fn get(&self, key: &str) -> Option<&Self> {
        match self {
            Self::Obj(fields) => fields.iter().find(|(k, _)| k == key).map(|(_, v)| v),
            _ => None,
        }
    }

    /// The elements of an array.
    pub fn arr(&self) -> Option<&[Self]> {
        match self {
            Self::Arr(a) => Some(a),
            _ => None,
        }
    }

    /// An integer, as `u64`.
    pub fn u64(&self) -> Option<u64> {
        match self {
            Self::Int(n) => u64::try_from(*n).ok(),
            _ => None,
        }
    }

    /// A boolean.
    pub fn bool(&self) -> Option<bool> {
        match self {
            Self::Bool(b) => Some(*b),
            _ => None,
        }
    }

    /// A string.
    pub fn str(&self) -> Option<&str> {
        match self {
            Self::Str(s) => Some(s),
            _ => None,
        }
    }
}

impl fmt::Display for Json {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Null => write!(f, "null"),
            Self::Bool(b) => write!(f, "{b}"),
            Self::Int(n) => write!(f, "{n}"),
            Self::Str(s) => write!(f, "{s:?}"),
            Self::Arr(a) => {
                write!(f, "[")?;
                for (k, v) in a.iter().enumerate() {
                    write!(f, "{}{v}", if k == 0 { "" } else { "," })?;
                }
                write!(f, "]")
            }
            Self::Obj(o) => {
                write!(f, "{{")?;
                for (k, (n, v)) in o.iter().enumerate() {
                    write!(f, "{}{n:?}:{v}", if k == 0 { "" } else { "," })?;
                }
                write!(f, "}}")
            }
        }
    }
}

struct Parser<'a> {
    s: &'a [u8],
    i: usize,
}

impl Parser<'_> {
    fn peek(&self) -> Option<u8> {
        self.s.get(self.i).copied()
    }

    fn ws(&mut self) {
        while matches!(self.peek(), Some(b' ' | b'\t' | b'\r' | b'\n')) {
            self.i += 1;
        }
    }

    fn eat(&mut self, c: u8) -> bool {
        self.ws();
        if self.peek() == Some(c) {
            self.i += 1;
            true
        } else {
            false
        }
    }

    fn word(&mut self, w: &str, v: Json) -> Result<Json, String> {
        if self.s.get(self.i..self.i + w.len()) == Some(w.as_bytes()) {
            self.i += w.len();
            Ok(v)
        } else {
            Err(format!("unexpected text at byte {}", self.i))
        }
    }

    fn string(&mut self) -> Result<String, String> {
        if !self.eat(b'"') {
            return Err(format!("expected a string at byte {}", self.i));
        }
        let mut out = Vec::new();
        loop {
            let c = self.peek().ok_or("an unterminated string")?;
            self.i += 1;
            match c {
                b'"' => return String::from_utf8(out).map_err(|e| e.to_string()),
                b'\\' => {
                    let e = self.peek().ok_or("an unterminated string")?;
                    self.i += 1;
                    out.push(match e {
                        b'n' => b'\n',
                        b't' => b'\t',
                        b'r' => b'\r',
                        b'"' | b'\\' | b'/' => e,
                        _ => return Err(format!("an escape the case files do not use at byte {}", self.i)),
                    });
                }
                _ => out.push(c),
            }
        }
    }

    fn value(&mut self) -> Result<Json, String> {
        self.ws();
        match self.peek().ok_or("unexpected end")? {
            b'{' => {
                self.i += 1;
                let mut fields = Vec::new();
                if self.eat(b'}') {
                    return Ok(Json::Obj(fields));
                }
                loop {
                    let k = self.string()?;
                    if !self.eat(b':') {
                        return Err(format!("expected : at byte {}", self.i));
                    }
                    fields.push((k, self.value()?));
                    if self.eat(b'}') {
                        return Ok(Json::Obj(fields));
                    }
                    if !self.eat(b',') {
                        return Err(format!("expected , or }} at byte {}", self.i));
                    }
                }
            }
            b'[' => {
                self.i += 1;
                let mut items = Vec::new();
                if self.eat(b']') {
                    return Ok(Json::Arr(items));
                }
                loop {
                    items.push(self.value()?);
                    if self.eat(b']') {
                        return Ok(Json::Arr(items));
                    }
                    if !self.eat(b',') {
                        return Err(format!("expected , or ] at byte {}", self.i));
                    }
                }
            }
            b'"' => self.string().map(Json::Str),
            b't' => self.word("true", Json::Bool(true)),
            b'f' => self.word("false", Json::Bool(false)),
            b'n' => self.word("null", Json::Null),
            _ => {
                let start = self.i;
                if self.peek() == Some(b'-') {
                    self.i += 1;
                }
                while matches!(self.peek(), Some(b'0'..=b'9')) {
                    self.i += 1;
                }
                let t =
                    std::str::from_utf8(self.s.get(start..self.i).unwrap_or_default()).map_err(|e| e.to_string())?;
                t.parse()
                    .map(Json::Int)
                    .map_err(|_| format!("expected a value at byte {start}"))
            }
        }
    }
}

/// One step of a case: the model's action, its arguments (the result among them) and the model's state after it.
#[derive(Debug, Clone)]
pub struct MbtStep {
    /// The action, `CallHold` for example.
    pub call: String,
    /// Its arguments, as the TLC label gives them.
    pub args: Vec<Json>,
    /// The model's variables after the call.
    pub state: Json,
}

impl fmt::Display for MbtStep {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}(", self.call)?;
        for (k, a) in self.args.iter().enumerate() {
            write!(f, "{}{a}", if k == 0 { "" } else { ", " })?;
        }
        write!(f, ")")
    }
}

/// One case: a path from the initial state of the model.
#[derive(Debug, Clone)]
pub struct MbtCase {
    /// Its number in the file.
    pub id: u64,
    /// The calls, in order.
    pub steps: Vec<MbtStep>,
}

impl MbtCase {
    fn from_json(v: &Json) -> Result<Self, String> {
        let id = v.get("case").and_then(Json::u64).ok_or("a case without a number")?;
        let mut steps = Vec::new();
        for s in v.get("steps").and_then(Json::arr).ok_or("a case without steps")? {
            steps.push(MbtStep {
                call: s
                    .get("call")
                    .and_then(Json::str)
                    .ok_or("a step without a call")?
                    .to_owned(),
                args: s
                    .get("args")
                    .and_then(Json::arr)
                    .ok_or("a step without arguments")?
                    .to_vec(),
                state: s.get("state").ok_or("a step without a state")?.clone(),
            });
        }
        Ok(Self { id, steps })
    }
}

/// The cases of one file: its first line, and the cases one at a time.
pub struct MbtCases {
    /// The first line: `constants`, `init`, and the counts of the graph and the cover.
    pub head: Json,
    lines: std::io::Lines<BufReader<std::fs::File>>,
}

impl Iterator for MbtCases {
    type Item = Result<MbtCase, String>;

    fn next(&mut self) -> Option<Self::Item> {
        let line = match self.lines.next()? {
            Ok(l) => l,
            Err(e) => return Some(Err(e.to_string())),
        };
        Some(Json::parse(&line).and_then(|v| MbtCase::from_json(&v)))
    }
}

/// The cases in the file `name` of the directory `$PINC_MBT_DIR`, `None` when the variable is unset.
///
/// # Errors
/// The file cannot be read or its first line is not the description of a graph.
pub fn mbt_cases(name: &str) -> Option<Result<MbtCases, String>> {
    let dir = std::env::var_os("PINC_MBT_DIR")?;
    let path = std::path::Path::new(&dir).join(name);
    Some((|| {
        let f = std::fs::File::open(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let mut lines = BufReader::new(f).lines();
        let first = lines.next().ok_or("an empty case file")?.map_err(|e| e.to_string())?;
        let head = Json::parse(&first)?;
        if head.get("constants").is_none() || head.get("init").is_none() {
            return Err(format!("{}: the first line does not describe a graph", path.display()));
        }
        Ok(MbtCases { head, lines })
    })())
}
